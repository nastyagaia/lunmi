function kindOf(category?: string, type?: string, name = ""): Kind {
  if (category === "Бьюти-гаджеты") return "gadget";
  if (category === "Для волос") return "hair";
  if (category === "Для тела") return "body";
  if (category === "Макияж") {
    if (type === "Для губ") return "lips";
    if (type === "Для глаз" || type === "Для бровей") return "eyes";
    return "face";
  }
  if (type === "SPF для лица" || /spf|sun/i.test(name)) return "spf";
  if (type === "Очищение") return "cleanse";
  if (type === "Маски" || type === "Пэды и патчи") return "mask";
  return "care";
}

/** Отзывы товара: у ~40 % товаров 1–3 отзыва, у остальных — пусто */
export function reviewsFor(id: string, category?: string, type?: string, name?: string): Review[] {
  const h = hash(id);
  if (h % 100 >= 40) return [];
  const count = 1 + (h % 3);
  const pool = POOL[kindOf(category, type, name)];
  const out: Review[] = [];
  const used = new Set<string>();
  for (let i = 0; i < count; i++) {
    const seed = hash(id + i);
    // примерно каждый седьмой отзыв — сдержанный, на 3–4 звезды
    const mid = seed % 7 === 0;
    let text = pick(mid ? pool.mid : pool.good, seed >>> 3);
    if (used.has(text)) text = pick(pool.good, (seed >>> 5) + i);
    if (used.has(text)) continue;
    used.add(text);
    out.push({
      name: pick(NAMES, seed >>> 7),
      date: DATES[Math.min(DATES.length - 1, i * 2 + ((seed >>> 11) % 3))],
      rating: mid ? 3 + ((seed >>> 13) % 2) : seed % 5 === 0 ? 4 : 5,
      text,
    });
  }
  return out;
}

/** Средняя оценка по отзывам: «4.7» */
export const averageRating = (list: Review[]) =>
  list.length ? (list.reduce((n, r) => n + r.rating, 0) / list.length).toFixed(1) : undefined;
